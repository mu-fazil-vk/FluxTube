import 'package:flutter_test/flutter_test.dart';
import 'package:fluxtube/domain/watch/models/explode/explode_watch.dart';
import 'package:fluxtube/domain/watch/models/invidious/video/adaptive_format.dart';
import 'package:fluxtube/domain/watch/models/invidious/video/caption.dart';
import 'package:fluxtube/domain/watch/models/invidious/video/format_stream.dart';
import 'package:fluxtube/domain/watch/models/invidious/video/invidious_watch_resp.dart';
import 'package:fluxtube/domain/watch/models/invidious/video/video_thumbnail.dart';
import 'package:fluxtube/domain/watch/models/piped/video/audio_stream.dart';
import 'package:fluxtube/domain/watch/models/piped/video/subtitle.dart';
import 'package:fluxtube/domain/watch/models/piped/video/video_stream.dart';
import 'package:fluxtube/domain/watch/models/piped/video/watch_resp.dart';
import 'package:fluxtube/domain/watch/playback/backend_to_newpipe_adapter.dart';
import 'package:fluxtube/domain/watch/playback/models/playback_configuration.dart';
import 'package:fluxtube/domain/watch/playback/newpipe_playback_resolver.dart';
import 'package:fluxtube/domain/watch/playback/newpipe_stream_helper.dart';
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

const _id = 'dQw4w9WgXcQ';
const _proxy = 'https://pipedproxy.example.com/videoplayback';

void main() {
  final resolver = NewPipePlaybackResolver();

  group('Piped', () {
    WatchResp piped({bool live = false}) => WatchResp(
          title: 'Piped video',
          uploader: 'Uploader',
          uploaderUrl: '/channel/UC123',
          thumbnailUrl: 'https://pipedproxy.example.com/vi/$_id/maxres.jpg',
          duration: 212,
          views: 1000,
          likes: 10,
          livestream: live,
          hls:
              live ? 'https://pipedproxy.example.com/live.m3u8' : 'fetching...',
          videoStreams: [
            VideoStream(
              url: '$_proxy?itag=18',
              format: 'MPEG_4',
              quality: '360p',
              mimeType: 'video/mp4',
              codec: 'avc1.42001E',
              videoOnly: false,
              fps: 30,
            ),
            VideoStream(
              url: '$_proxy?itag=299',
              format: 'MPEG_4',
              quality: '1080p60',
              mimeType: 'video/mp4',
              codec: 'avc1.64002a',
              videoOnly: true,
              fps: 60,
              height: 1080,
              initStart: 0,
              initEnd: 740,
              indexStart: 741,
              indexEnd: 1500,
            ),
            VideoStream(
              url: '$_proxy?itag=136',
              format: 'MPEG_4',
              quality: '720p',
              mimeType: 'video/mp4',
              videoOnly: true,
              fps: 30,
            ),
          ],
          audioStreams: [
            AudioStream(
              url: '$_proxy?itag=140',
              format: 'M4A',
              mimeType: 'audio/mp4',
              codec: 'mp4a.40.2',
              bitrate: 130000,
              audioTrackType: 'ORIGINAL',
              audioTrackLocale: 'en',
            ),
            AudioStream(
              url: '$_proxy?itag=140&xtags=acont%3Ddubbed-auto%3Alang%3Des',
              format: 'M4A',
              mimeType: 'audio/mp4',
              bitrate: 130000,
            ),
          ],
          subtitles: [
            Subtitle(
              url: 'https://pipedproxy.example.com/api/timedtext?lang=en',
              mimeType: 'text/vtt',
              code: 'en',
              autoGenerated: false,
            ),
          ],
          chapters: [
            {'title': 'Intro', 'start': 0, 'image': 'https://x/0.jpg'},
            {'title': 'Main', 'start': 60, 'image': 'https://x/1.jpg'},
          ],
        );

    test('maps streams and resolves a merging config', () {
      final resp = newPipeRespFromPiped(piped(), videoId: _id);

      expect(resp.id, _id);
      expect(resp.hlsUrl, isNull, reason: 'placeholder must be dropped');
      expect(resp.videoStreams, hasLength(1));
      expect(resp.videoOnlyStreams, hasLength(2));
      expect(resp.videoOnlyStreams!.first.resolution, '1080p');
      expect(resp.audioStreams!.first.averageBitrate, 130);
      expect(resp.chapters!.map((c) => c.startTimeSeconds), [0, 60]);
      expect(resp.subtitles!.single.url, startsWith('https://pipedproxy'));

      final labels = resolver.getAvailableQualityLabels(resp);
      expect(labels, containsAll(['1080p 60fps', '720p', '360p']));

      final config = resolver.resolve(
        watchResp: resp,
        preferredQuality: '720p',
      );
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.merging);
      expect(config.videoUrl, '$_proxy?itag=136');
      expect(config.audioUrl, startsWith(_proxy));
    });

    test('exposes dubbed audio as a separate track', () {
      final resp = newPipeRespFromPiped(piped(), videoId: _id);
      final tracks =
          NewPipeStreamHelper.getAvailableAudioTracks(resp.audioStreams!);
      expect(tracks, hasLength(2));
      expect(tracks.first.isOriginal, isTrue);
      expect(tracks.last.isDubbed, isTrue);
      expect(tracks.last.locale, 'es');
    });

    test('live uses proxied HLS', () {
      final resp = newPipeRespFromPiped(piped(live: true), videoId: _id);
      final config =
          resolver.resolve(watchResp: resp, preferredQuality: '720p');
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.hls);
      expect(config.isLive, isTrue);
      expect(config.manifestUrl, 'https://pipedproxy.example.com/live.m3u8');
    });
  });

  group('Invidious', () {
    const base = 'https://inv.example.com';
    final inv = InvidiousWatchResp(
      title: 'Invidious video',
      videoId: _id,
      author: 'Author',
      authorId: 'UC456',
      lengthSeconds: 300,
      published: 1700000000,
      videoThumbnails: [
        VideoThumbnail(quality: 'maxres', url: '/vi/$_id/maxres.jpg'),
      ],
      dashUrl: '$base/api/manifest/dash/id/$_id',
      formatStreams: [
        FormatStream(
          url: 'https://rr1.googlevideo.com/videoplayback?itag=18',
          itag: '18',
          type: 'video/mp4; codecs="avc1.42001E, mp4a.40.2"',
          qualityLabel: '360p',
          size: '640x360',
          container: 'mp4',
        ),
      ],
      adaptiveFormats: [
        AdaptiveFormat(
          url: 'https://rr1.googlevideo.com/videoplayback?itag=137',
          itag: '137',
          type: 'video/mp4; codecs="avc1.640028"',
          bitrate: '4000000',
          init: '0-740',
          index: '741-1900',
          qualityLabel: '1080p',
          size: '1920x1080',
          fps: 30,
          container: 'mp4',
        ),
        AdaptiveFormat(
          url: 'https://rr1.googlevideo.com/videoplayback?itag=140',
          itag: '140',
          type: 'audio/mp4; codecs="mp4a.40.2"',
          bitrate: '130000',
          container: 'm4a',
          audioQuality: 'AUDIO_QUALITY_MEDIUM',
        ),
      ],
      captions: [
        Caption(
          label: 'English',
          languageCode: 'en',
          url: '/api/v1/captions/$_id?label=English',
        ),
      ],
    );

    test('maps streams, resolves relative urls and merges', () {
      final resp =
          newPipeRespFromInvidious(inv, videoId: _id, instanceBaseUrl: base);

      expect(resp.thumbnailUrl, '$base/vi/$_id/maxres.jpg');
      expect(resp.uploaderUrl, '/channel/UC456');
      expect(resp.subtitles!.single.url,
          '$base/api/v1/captions/$_id?label=English');
      expect(resp.videoOnlyStreams!.single.mimeType, 'video/mp4');
      expect(resp.videoOnlyStreams!.single.codec, 'avc1.640028');
      expect(resp.videoOnlyStreams!.single.hasDashInfo, isTrue);
      expect(resp.audioStreams!.single.averageBitrate, 130);
      expect(resp.audioStreams!.single.format, 'M4A');

      final config =
          resolver.resolve(watchResp: resp, preferredQuality: '1080p');
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.merging);
      expect(config.videoUrl, contains('itag=137'));
      expect(config.audioUrl, contains('itag=140'));
    });

    test('Auto quality prefers the instance DASH manifest', () {
      final resp =
          newPipeRespFromInvidious(inv, videoId: _id, instanceBaseUrl: base);
      final config = resolver.resolve(
        watchResp: resp,
        preferredQuality: '720p',
        preferAdaptive: true,
      );
      expect(config.sourceType, MediaSourceType.dash);
      expect(config.manifestUrl, '$base/api/manifest/dash/id/$_id');
    });

    test('drops captions with relative urls when no base is given', () {
      final resp = newPipeRespFromInvidious(inv, videoId: _id);
      expect(resp.subtitles, isEmpty);
    });
  });

  group('Explode', () {
    final video = ExplodeWatchResp(
      id: _id,
      title: 'Explode video',
      author: 'Author',
      channelId: 'UC789',
      uploadDate: DateTime.utc(2024),
      description: '0:00 Intro',
      duration: const Duration(minutes: 3),
      thumbnailUrl: 'https://i.ytimg.com/vi/$_id/maxresdefault.jpg',
      viewCount: 5,
      likeCount: 1,
      dislikeCount: 0,
      isLive: false,
    );

    Map<String, dynamic> common(int tag, String url, int bps) => {
          'videoId': {'value': _id},
          'tag': tag,
          'url': url,
          'size': {'totalBytes': 1000},
          'bitrate': {'bitsPerSecond': bps},
          'fragments': <dynamic>[],
        };

    final manifest = StreamManifest([
      MuxedStreamInfo.fromJson({
        ...common(
            18, 'https://rr1.googlevideo.com/videoplayback?itag=18', 500000),
        'container': {'name': 'mp4'},
        'audioCodec': 'mp4a.40.2',
        'videoCodec': 'avc1.42001E',
        'qualityLabel': '360p',
        'videoQuality': 'medium360',
        'videoResolution': {'width': 640, 'height': 360},
        'framerate': {'framesPerSecond': 30},
        'codec': 'video/mp4; codecs="avc1.42001E, mp4a.40.2"',
      }),
      VideoOnlyStreamInfo.fromJson({
        ...common(
            298, 'https://rr1.googlevideo.com/videoplayback?itag=298', 3000000),
        'container': {'name': 'mp4'},
        'videoCodec': 'avc1.4d4020',
        'qualityLabel': '720p60',
        'videoQuality': 'high720',
        'videoResolution': {'width': 1280, 'height': 720},
        'framerate': {'framesPerSecond': 60},
        'codec': 'video/mp4; codecs="avc1.4d4020"',
      }),
      AudioOnlyStreamInfo.fromJson({
        ...common(
            140, 'https://rr1.googlevideo.com/videoplayback?itag=140', 128000),
        'container': {'name': 'mp4'},
        'audioCodec': 'mp4a.40.2',
        'qualityLabel': 'tiny',
        'codec': 'audio/mp4; codecs="mp4a.40.2"',
        'audioTrack': {
          'displayName': 'English original',
          'id': 'en.4',
          'audioIsDefault': true,
        },
      }),
    ]);

    final subtitles = [
      {
        'code': 'en',
        'name': 'English',
        'url': 'https://www.youtube.com/api/timedtext?v=$_id&fmt=vtt',
      },
      {
        'code': 'en',
        'name': 'English (auto-generated)',
        'url': 'https://www.youtube.com/api/timedtext?v=$_id&kind=asr&fmt=vtt',
      },
    ];

    test('muxed-only input resolves to progressive', () {
      final resp = newPipeRespFromExplode(
        video,
        videoId: _id,
        muxedStreams:
            manifest.muxed.map(MyMuxedStreamInfo.fromYoutubeStream).toList(),
        subtitles: subtitles,
      );
      expect(resp.videoStreams!.single.resolution, '360p');
      expect(resp.subtitles, hasLength(1));
      expect(resp.subtitles!.single.autoGenerated, isFalse);
      expect(resp.uploaderUrl, '/channel/UC789');

      final config =
          resolver.resolve(watchResp: resp, preferredQuality: '720p');
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.progressive);
      expect(config.videoUrl, contains('itag=18'));
    });

    test('full manifest enables merging and audio tracks', () {
      final resp =
          newPipeRespFromExplode(video, videoId: _id, manifest: manifest);
      expect(resp.audioStreams!.single.averageBitrate, 128);
      expect(resp.audioStreams!.single.audioLocale, 'en');

      final config =
          resolver.resolve(watchResp: resp, preferredQuality: '720p');
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.merging);
      expect(config.qualityLabel, '720p 60fps');
      expect(config.videoUrl, contains('itag=298'));
      expect(config.audioUrl, contains('itag=140'));

      final tracks =
          NewPipeStreamHelper.getAvailableAudioTracks(resp.audioStreams!);
      expect(tracks.single.isOriginal, isTrue);
    });

    test('live url maps to HLS', () {
      final resp = newPipeRespFromExplode(
        video,
        videoId: _id,
        liveUrl: 'https://manifest.googlevideo.com/live.m3u8',
      );
      final config =
          resolver.resolve(watchResp: resp, preferredQuality: '720p');
      expect(config.isValid, isTrue);
      expect(config.sourceType, MediaSourceType.hls);
      expect(config.isLive, isTrue);
    });
  });
}
